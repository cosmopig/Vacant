def test_manifest_dropped_but_agent_edits_in_official_test_paths_kept(fixture, tmp_path):
    workspace, _ = fixture
    base = tmp_path / 'baseline'
    git(workspace, 'clone', '--quiet', '--no-local', str(workspace), str(base))
    (workspace / 'test_old.py').write_text('def test_old(): assert True\ndef test_agent_old(): assert False\n')
    content = patch.derive_patch(base, workspace, '--- a/test_old.py\n+++ b/test_old.py\n').decode()
    assert 'VACANT_TESTS.txt' not in content
    assert '+++ b/test_agent.py' in content and '+def test_agent_old()' in content
    assert '+++ b/behavior.py' in content
    subprocess.run(['git', 'apply', '-'], cwd=base, input=content.encode(), check=True)
    assert (base / 'test_agent.py').read_bytes() == (workspace / 'test_agent.py').read_bytes()


