"""rc4：agent（或驗收時跑的候選碼）不能透過副本裡的 node_modules symlink 改到使用者專案。
重現（rc3.1 查證）：m.test.js 用 node_modules/helper 判斷；agent 把 helper 改成永遠 true ⇒ rc3.1 判 PASS、原專案的 helper 被改。"""
import os
import shutil
import stat
import sys

import pytest

from vacant_network.adapters import cli as adapters_cli

needs_node = pytest.mark.skipif(not (shutil.which("node") and shutil.which("npm")), reason="node/npm missing")
HELPER = "module.exports.check = function (v) { return v === 2; };\n"


def _proj(tmp_path):
    p = tmp_path / "proj"
    (p / "node_modules" / "helper").mkdir(parents=True)
    (p / "node_modules" / "helper" / "index.js").write_text(HELPER)
    (p / "package.json").write_text('{"name":"m","version":"1.0.0","scripts":{"test":"node m.test.js"}}')
    (p / "m.js").write_text("module.exports = { v: 1 };\n")
    (p / "m.test.js").write_text('if (!require("helper").check(require("./m.js").v)) { process.exit(1); }\n')
    return p


def _run(tmp_path, monkeypatch, p, agent_src, attempts="1"):
    agent = tmp_path / "agent.py"
    agent.write_text(agent_src)
    monkeypatch.setenv("VACANT_WORK", str(tmp_path / "work"))
    monkeypatch.setenv("VACANT_HOME", str(tmp_path / "home"))
    monkeypatch.chdir(p)
    return adapters_cli.main(["do", "--cmd", f"{sys.executable} {agent} {{prompt}}", "--prompt", "x",
                              "--attempts", attempts, "--timeout", "120"])


def _modes(root):
    out = {}
    for dp, dns, fns in os.walk(root):
        for n in [dp] + [os.path.join(dp, x) for x in fns]:
            out[n] = stat.S_IMODE(os.lstat(n).st_mode)
    return out


@needs_node
def test_agent_cannot_rewrite_helper_through_symlink(tmp_path, monkeypatch, capsys):
    p = _proj(tmp_path)
    before = _modes(p / "node_modules")
    src = ("import pathlib\n"
           "try:\n"
           "    pathlib.Path('node_modules/helper/index.js').write_text('module.exports.check=function(){return true}\\n')\n"
           "except OSError:\n"
           "    pass\n"
           "pathlib.Path('note.txt').write_text('hi\\n')\n")
    rc = _run(tmp_path, monkeypatch, p, src, attempts="2")
    out = capsys.readouterr().out
    assert (p / "node_modules" / "helper" / "index.js").read_text() == HELPER, "user's node_modules must be untouched"
    assert rc != 0, out
    assert (p / "m.js").read_text() == "module.exports = { v: 1 };\n"
    assert _modes(p / "node_modules") == before, "write bits must be restored after the run"


@needs_node
def test_agent_that_forces_write_is_detected_and_nothing_written_back(tmp_path, monkeypatch, capsys):
    """agent 透過絕對路徑自己把原專案 node_modules 權限改回來再寫：擋不住，但內容清單一定要抓到——不放行、停下、不寫回、訊息列出路徑。"""
    p = _proj(tmp_path)
    orig_helper = p / "node_modules" / "helper" / "index.js"
    src = ("import os, pathlib, stat\n"
           f"f = pathlib.Path({str(orig_helper)!r})\n"
           "os.chmod(f.parent, 0o755); os.chmod(f, 0o644)\n"
           "f.write_text('module.exports.check=function(){return true}\\n')\n"
           "pathlib.Path('note.txt').write_text('hi\\n')\n")
    rc = _run(tmp_path, monkeypatch, p, src, attempts="3")
    out = capsys.readouterr().out
    assert rc == adapters_cli.EXIT["void"], out
    assert "changed the project's node_modules" in out
    assert "helper/index.js" in out
    assert "attempt 2" not in out
    assert not (p / "note.txt").exists(), "nothing may be written back after node_modules changed"


@needs_node
def test_candidate_code_writing_node_modules_during_check_is_caught(tmp_path, monkeypatch, capsys):
    """驗收時跑的是候選碼：m.js 在被 require 時改 helper ⇒ 也不能放行。"""
    p = _proj(tmp_path)
    evil = ("const fs=require('fs'),path=require('path');"
            "const f=path.join(__dirname,'node_modules','helper','index.js');"
            "try{fs.chmodSync(path.dirname(f),0o755);fs.chmodSync(f,0o644);"
            "fs.writeFileSync(f,'module.exports.check=function(){return true}\\n')}catch(e){}"
            "module.exports={v:1};\n")
    rc = _run(tmp_path, monkeypatch, p, f"import pathlib\npathlib.Path('m.js').write_text({evil!r})\n")
    out = capsys.readouterr().out
    assert rc != 0, out
    assert (p / "m.js").read_text() == "module.exports = { v: 1 };\n"


@needs_node
def test_honest_fix_still_passes_and_modes_restored(tmp_path, monkeypatch, capsys):
    p = _proj(tmp_path)
    before = _modes(p / "node_modules")
    rc = _run(tmp_path, monkeypatch, p, "import pathlib\npathlib.Path('m.js').write_text('module.exports = { v: 2 };\\n')\n")
    out = capsys.readouterr().out
    assert rc == 0, out
    assert (p / "m.js").read_text() == "module.exports = { v: 2 };\n"
    assert _modes(p / "node_modules") == before
