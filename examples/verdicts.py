UNREVIEWED = "未複驗"
"""沒有裁決條目時索引裡填的值。**不等於通過**——沒送去複驗過的宣稱，
它的地位是「還沒有人試過推翻它」，而不是「有人試過但推不倒」。"""


def verdict_for(claim_id: str) -> dict[str, str]:
    """回傳可直接併進宣稱條目的裁決欄位。未複驗者也明確標出來，不留空白。"""
    v = VERDICTS.get(claim_id)
    return dict(v) if v else {"verdict": UNREVIEWED}
